#!/usr/bin/env sh
set -eu

PROJECT_PATH="${UNITY_PROJECT_PATH:-UnityProject}"
VERSION="${UNITY_VERSION:-7000.0.0a8}"
VERSION_FILE="$PROJECT_PATH/ProjectSettings/ProjectVersion.txt"
MANIFEST="$PROJECT_PATH/Packages/manifest.json"
SCENE="$PROJECT_PATH/Assets/Scenes/OmnisMain.unity"
SCENE_META="$SCENE.meta"
BUILD_SETTINGS="$PROJECT_PATH/ProjectSettings/EditorBuildSettings.asset"
GRAPHICS_SETUP="$PROJECT_PATH/Assets/Editor/OmnisGraphicsSetup.cs"
BUILD_SCRIPT="$PROJECT_PATH/Assets/Editor/OmnisBuild.cs"

test -f "$VERSION_FILE"
grep -q "^m_EditorVersion: $VERSION" "$VERSION_FILE"
test -f "$MANIFEST"
grep -q '"com.unity.inputsystem"' "$MANIFEST"
grep -q '"com.unity.render-pipelines.universal"' "$MANIFEST"

test -f "$SCENE"
test -f "$SCENE_META"
grep -q 'guid: c5d70f8a9b62469db342a95e7f0c81a4' "$SCENE_META"
grep -q 'guid: b7a4c2d18f6e4a2c9b30d5e7a1f4c608' "$SCENE"
test -f "$BUILD_SETTINGS"
grep -q 'Assets/Scenes/OmnisMain.unity' "$BUILD_SETTINGS"

test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisPlayerController.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisGameState.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisInteractable.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisSentinel.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldBootstrap.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldSimulation.cs"
grep -q "AddComponent<OmnisWorldSimulation>" "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldBootstrap.cs"
grep -q "WeatherLabel" "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldSimulation.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisResonanceCombat.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisResonanceCombat.cs.meta"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/Omnis.Runtime.asmdef"
test -f "$PROJECT_PATH/Assets/Tests/PlayMode/Omnis.PlayModeTests.asmdef"
test -f "$PROJECT_PATH/Assets/Tests/PlayMode/OmnisResonanceCombatPlayModeTests.cs"
grep -q 'com.unity.test-framework' "$MANIFEST"
grep -q 'AddComponent<OmnisResonanceCombat>' "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldBootstrap.cs"
grep -q 'BuildOpenWorldExpansion' "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldBootstrap.cs"
grep -q 'Wayfarer Village Plaza' "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldBootstrap.cs"
grep -q 'Aether River Segment' "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldBootstrap.cs"
grep -q 'Far Horizon Basalt Ridge' "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisWorldBootstrap.cs"
grep -q 'RegisterMeleeHit' "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisPlayerController.cs"
test -f "$PROJECT_PATH/Assets/Omnis/Scripts/OmnisAudioDirector.cs"
test -f "$GRAPHICS_SETUP"
grep -q '3840' "$GRAPHICS_SETUP"
grep -q '2160' "$GRAPHICS_SETUP"
grep -q 'BuildWindows' "$BUILD_SCRIPT"
grep -q 'BuildLinux' "$BUILD_SCRIPT"
grep -q 'activeInputHandler' "$GRAPHICS_SETUP"

echo "Unity project structure checks passed for Editor $VERSION (scene, GUIDs, gameplay sources and build entry points found)."
echo "IMPORTANT: this does not verify package compatibility or C# compilation. Unity Editor import, PlayMode tests, build and launch are mandatory gates."
